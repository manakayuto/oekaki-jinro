  // 最近出たお題を避けて1つ選ぶ。recent は表示名の配列（新しいものが後ろ）。
  function pick(cat, recent) {
    const cats = Object.keys(T);
    const c = T[cat] ? cat : cats[Math.floor(Math.random() * cats.length)];
    const seen = new Set(recent || []);
    let pool = T[c].filter(e => !seen.has(e[0]));
    if (!pool.length) pool = T[c].filter(e => e[0] !== (recent || [])[(recent || []).length - 1]);
    if (!pool.length) pool = T[c];
    const e = pool[Math.floor(Math.random() * pool.length)];
    return { cat: c, word: e[0], alias: e.slice(1) };
  }
  // 覚えておく数：全お題の半分まで（ジャンル指定でも一周するまで重ならない）
  function remember(recent, word) {
    const max = Math.floor(Object.values(T).reduce((n, l) => n + l.length, 0) / 2);
    return [...(recent || []).filter(w => w !== word), word].slice(-max);
  }
  window.EJR_TOPICS = { list: T, cats: Object.keys(T), pick, remember };
